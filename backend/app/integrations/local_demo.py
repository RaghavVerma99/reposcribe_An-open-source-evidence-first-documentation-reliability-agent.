"""Local demo provider.

This is NOT a language model. It produces deterministic, rule-based text from
retrieved evidence so the product is usable and testable without credentials.
Every surface labels it as demo mode.
"""

from __future__ import annotations

import difflib
import re

from app.analyzers.common import RepoIndex
from app.core.errors import AppError
from app.core.settings import Settings
from app.integrations.model_provider import Chunk, PatchProposal
from app.schemas.models import Citation, Finding, GroundedAnswer, ProviderStatus

MODE_LABEL = "local_demo"
MAX_CHANGED_LINES = 40

ROUTE_PAIR_RE = re.compile(r"`([A-Z]{3,7})\s+(/[^`\s]*)`")
BACKTICK_RE = re.compile(r"`([^`]+)`")


class LocalDemoProvider:
    name = "local-demo"

    def __init__(self, settings: Settings) -> None:
        self.settings = settings

    def status(self) -> ProviderStatus:
        return ProviderStatus(
            mode="local_demo",
            provider=self.name,
            model="rule-based extractive demo",
            state="connected",
            message="Running in local demo mode. No language model is contacted; answers and patches are rule-based.",
            verified_contract=False,
        )

    def answer_question(self, question: str, chunks: list[Chunk]) -> GroundedAnswer:
        if not chunks:
            return GroundedAnswer(
                answer=(
                    "I couldn't find repository evidence that answers this question. "
                    "Try naming a file, route, or symbol that exists in the inspected snapshot."
                ),
                citations=[],
                limitations=[
                    "No retrieved excerpt matched the question terms.",
                    "Local demo mode performs lexical retrieval only; there is no semantic search.",
                ],
                follow_up_suggestions=[
                    "What routes are defined in this repository?",
                    "How is the application configured?",
                ],
                mode=MODE_LABEL,
            )

        citations = [
            Citation(
                path=chunk.path,
                start_line=chunk.start_line,
                end_line=chunk.end_line,
                excerpt=chunk.text,
            )
            for chunk in chunks[:4]
        ]
        highlights = _highlights(chunks[0].text, question)
        answer_lines = [
            f"From the inspected repository, {len(chunks)} matching location(s) were retrieved.",
            "",
            f"`{chunks[0].path}:{chunks[0].start_line}`",
        ]
        if highlights:
            answer_lines.extend(f"- {line}" for line in highlights[:4])
        else:
            answer_lines.append("- " + chunks[0].text.splitlines()[0].strip())
        if len(chunks) > 1:
            answer_lines.append("")
            answer_lines.append(
                "Other matches: " + ", ".join(f"`{chunk.path}:{chunk.start_line}`" for chunk in chunks[1:4]) + "."
            )

        return GroundedAnswer(
            answer="\n".join(answer_lines),
            citations=citations,
            limitations=[
                "Local demo mode: this answer is extracted from file excerpts by rules, not generated by a language model.",
                "Only the indexed snapshot is searched; files excluded from indexing cannot appear here.",
            ],
            follow_up_suggestions=[
                "Show the documented routes.",
                "Which documentation files were inspected?",
            ],
            mode=MODE_LABEL,
        )

    def draft_patch(
        self, finding: Finding, document: str, doc_path: str, index: RepoIndex
    ) -> PatchProposal:
        if finding.check_id == "fastapi.route_matches_docs":
            return _patch_route(finding, document)
        if finding.check_id == "markdown.internal_link_exists":
            return _patch_link(finding, document, index)
        if finding.check_id == "python.public_symbol_referenced":
            return _patch_symbol(finding, document, index)
        raise AppError(
            "patch_not_available",
            "No safe minimal documentation change can be derived automatically for this check.",
            422,
        )


def _patch_route(finding: Finding, document: str) -> PatchProposal:
    """Repair a documented route against the closest discoverable route.

    Rules:
    - Only lines that mention both the documented method and the documented
      path are rewritten. A bare path substring match would also rewrite a
      different row (for example ``DELETE /api/users/{user_id}`` while fixing
      ``GET /api/users``), inventing a route the code does not define.
    - Method and path are only rewritten when the change is unambiguous.
    - A combined method-and-path change is rejected: it implies two
      independent claims drifted, and an automated fix would require a
      human reviewer.
    - When the closest route is from an unresolved prefix or the path
      similarity is low, the proposal is also rejected.
    """
    claim = ROUTE_PAIR_RE.search(finding.documentation_claim or "")
    observed = ROUTE_PAIR_RE.search(finding.observed_fact or "")
    if not claim or not observed:
        raise AppError(
            "patch_not_available",
            "The documented and observed routes could not be paired for a minimal edit.",
            422,
        )
    old_method, old_path = claim.group(1), claim.group(2)
    new_method, new_path = observed.group(1), observed.group(2)
    path_changed = new_path != old_path
    method_changed = new_method != old_method

    if not path_changed and not method_changed:
        raise AppError(
            "patch_not_available",
            "The documented route already matches source; no patch is needed.",
            422,
        )
    if method_changed and path_changed:
        raise AppError(
            "patch_not_available",
            "Both the documented method and path differ from source. "
            "An automated fix would require a human reviewer.",
            422,
        )
    if (new_path != "/" and old_path != "/") and path_changed:
        ratio = difflib.SequenceMatcher(None, old_path, new_path).ratio()
        if ratio < 0.4:
            raise AppError(
                "patch_not_available",
                "The closest discovered route is too dissimilar to the documented one for a safe rewrite.",
                422,
            )

    lines = document.splitlines(keepends=True)
    changed = 0
    for index, line in enumerate(lines):
        # Both parts of the claim must appear on the same line. That keeps the
        # edit on the documented route that produced this finding and leaves
        # neighbouring rows for their own findings.
        if old_path not in line or not _mentions_method(line, old_method):
            continue
        updated = line
        if path_changed:
            updated = updated.replace(old_path, new_path)
        if method_changed:
            updated = re.sub(rf"\b{re.escape(old_method)}\b", new_method, updated, count=1)
        if updated != line:
            lines[index] = updated
            changed += 1
    if not changed:
        raise AppError(
            "patch_not_available",
            "The documented method and path were not found together on one line of the target document.",
            422,
        )

    if path_changed:
        rationale = f"Updated the documented path from {old_path} to {new_path}."
    else:
        rationale = f"Updated the documented method from {old_method} to {new_method}."
    limitations: list[str] = []
    if "Closest discovered route" in (finding.observed_fact or ""):
        limitations.append(
            "Replacement uses the closest discoverable route; review it before applying."
        )
    return PatchProposal(content="".join(lines), rationale=rationale, limitations=limitations)


def _patch_link(finding: Finding, document: str, index: RepoIndex) -> PatchProposal:
    target = _first_backtick(finding.documentation_claim or "")
    if not target or target.startswith(("http://", "https://", "#")):
        raise AppError("patch_not_available", "The broken link target could not be parsed.", 422)

    path_part, _, anchor = target.partition("#")
    candidate = _closest_existing(path_part, index)
    if candidate and candidate != path_part:
        replacement = candidate + (f"#{anchor}" if anchor else "")
        new_document = document.replace(f"]({target})", f"]({replacement})")
        rationale = f"Repointed `{target}` to the existing file `{replacement}`."
        limitations = ["The replacement was chosen by filename similarity; review it before applying."]
    else:
        new_document = _de_link(document, target)
        rationale = f"Removed the broken link to `{target}` and kept its text."
        limitations = ["The reference was removed rather than repointed, because no existing file matched."]

    if new_document == document:
        raise AppError("patch_not_available", "The broken link text was not found in the target document.", 422)
    return PatchProposal(content=new_document, rationale=rationale, limitations=limitations)


def _patch_symbol(finding: Finding, document: str, index: RepoIndex) -> PatchProposal:
    token = _first_backtick(finding.documentation_claim or "")
    if not token:
        raise AppError("patch_not_available", "The documented symbol could not be parsed.", 422)
    names = {symbol.name for symbol in index.symbols}
    if not names:
        raise AppError("patch_not_available", "No symbols were indexed.", 422)
    closest = max(names, key=lambda name: difflib.SequenceMatcher(None, token.split(".")[-1], name).ratio())
    ratio = difflib.SequenceMatcher(None, token.split(".")[-1], closest).ratio()
    if ratio < 0.75:
        raise AppError("patch_not_available", "No indexed symbol is close enough to propose a safe replacement.", 422)
    new_token = token.rsplit(".", 1)[0] + "." + closest if "." in token else closest
    new_document = document.replace(f"`{token}`", f"`{new_token}`")
    if new_document == document:
        raise AppError("patch_not_available", "The symbol reference was not found in the target document.", 422)
    return PatchProposal(
        content=new_document,
        rationale=f"Updated `{token}` to the indexed symbol `{new_token}`.",
        limitations=["Replacement is based on name similarity within the static index."],
    )


def _mentions_method(line: str, method: str) -> bool:
    return re.search(rf"\b{re.escape(method)}\b", line) is not None


def _first_backtick(text: str) -> str | None:
    match = BACKTICK_RE.search(text)
    return match.group(1).strip() if match else None


def _closest_existing(target: str, index: RepoIndex) -> str | None:
    name = target.rsplit("/", 1)[-1]
    candidates = [path for path in index.docs if path.rsplit("/", 1)[-1] == name]
    if len(candidates) == 1:
        return candidates[0]
    all_docs = list(index.docs)
    if not all_docs:
        return None
    closest = max(all_docs, key=lambda path: difflib.SequenceMatcher(None, target, path).ratio())
    score = difflib.SequenceMatcher(None, target, closest).ratio()
    return closest if score >= 0.7 else None


def _de_link(document: str, target: str) -> str:
    pattern = re.compile(r"\[([^\]]+)\]\(\s*" + re.escape(target) + r"\s*\)")
    return pattern.sub(lambda match: match.group(1), document)


def _highlights(text: str, question: str) -> list[str]:
    terms = [term for term in re.split(r"\W+", question.lower()) if len(term) > 2]
    hits = []
    for line in text.splitlines():
        if any(term in line.lower() for term in terms):
            stripped = line.strip()
            if stripped:
                hits.append(stripped[:200])
        if len(hits) >= 4:
            break
    return hits


