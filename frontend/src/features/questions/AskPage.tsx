import { useRef, useState } from "react";
import { Link } from "react-router-dom";

import { useAppState } from "../../app/AppState";
import { api, ApiError } from "../../lib/api";
import { useShell } from "../../lib/shell";
import { usePageTitle } from "../../lib/usePageTitle";
import {
  Button,
  Card,
  ErrorNotice,
  PageHeader,
  ProviderPill,
  Spinner,
} from "../../components/ui/Primitives";

const EXAMPLES = [
  "Which endpoints does this service expose?",
  "How is the application configured?",
  "What does the README tell a new contributor to run?",
  "Where are user routes defined?",
];

interface Exchange {
  id: string;
  question: string;
  answer?: Awaited<ReturnType<typeof api.ask>>;
  error?: ApiError;
}

export default function AskPage() {
  const { repository } = useShell();
  const { provider } = useAppState();
  const [question, setQuestion] = useState("");
  const [exchanges, setExchanges] = useState<Exchange[]>([]);
  const [pending, setPending] = useState(false);
  const nextExchangeId = useRef(0);
  usePageTitle("Ask RepoScribe");

  async function ask(id: string, asked: string) {
    setPending(true);
    try {
      const answer = await api.ask(repository.id, asked);
      setExchanges((current) =>
        current.map((item) => (item.id === id ? { ...item, answer, error: undefined } : item)),
      );
    } catch (caught) {
      setExchanges((current) =>
        current.map((item) =>
          item.id === id ? { ...item, error: caught as ApiError } : item,
        ),
      );
    } finally {
      setPending(false);
    }
  }

  function submit(text: string) {
    const asked = text.trim();
    if (!asked || pending) return;
    setQuestion("");
    nextExchangeId.current += 1;
    const id = `exchange-${nextExchangeId.current}`;
    setExchanges((current) => [...current, { id, question: asked }]);
    void ask(id, asked);
  }

  function retry(id: string) {
    if (pending) return;
    const exchange = exchanges.find((item) => item.id === id);
    if (!exchange) return;
    setExchanges((current) =>
      current.map((item) =>
        item.id === id ? { ...item, answer: undefined, error: undefined } : item,
      ),
    );
    void ask(id, exchange.question);
  }

  const providerCopy = !provider
    ? "Checking provider status…"
    : provider.mode === "unavailable"
      ? provider.message
      : provider.mode === "live"
        ? `Answers are generated by the ${provider.provider} provider (${provider.model}). Citations are still checked against retrieved excerpts.`
        : "Local demo mode answers are extracted from retrieved file excerpts by rules. No language model is contacted.";

  return (
    <div>
      <PageHeader
        title="Ask RepoScribe"
        subtitle="Answers are limited to the inspected snapshot. Every citation points at a real retrieved excerpt."
        meta={
          <span className="flex flex-wrap items-center gap-x-2 gap-y-1">
            <span className="font-mono text-ink">{repository.name}</span>
            <span aria-hidden="true" className="text-line-strong">
              ·
            </span>
            <span className="font-mono text-ink">{repository.id}</span>
          </span>
        }
        actions={
          provider ? (
            <ProviderPill mode={provider.mode} message={provider.message} className="h-8" />
          ) : null
        }
      />

      <div className="space-y-6 p-4 sm:p-6 lg:p-8">
        <Card className="px-5 py-5">
          <p className="eyebrow">Ask the snapshot</p>
          <form
            onSubmit={(event) => {
              event.preventDefault();
              void submit(question);
            }}
            className="mt-3 flex flex-col gap-2.5 sm:flex-row"
          >
            <label htmlFor="question" className="sr-only">
              Question about this repository
            </label>
            <input
              id="question"
              value={question}
              maxLength={500}
              onChange={(event) => setQuestion(event.target.value)}
              placeholder="Ask about routes, configuration, setup instructions…"
              className="h-10 flex-1 rounded-control border border-line bg-canvas px-3.5 text-[13px] text-ink transition-colors placeholder:text-ink-faint hover:border-line-strong focus:border-accent/45"
            />
            <Button
              type="submit"
              variant="primary"
              loading={pending}
              disabled={!question.trim()}
              className="h-10 px-5"
            >
              Ask
            </Button>
          </form>

          <div className="mt-3 flex flex-wrap gap-2">
            {EXAMPLES.map((example) => (
              <button
                key={example}
                type="button"
                disabled={pending}
                onClick={() => submit(example)}
                className="inline-flex items-center rounded-full border border-line bg-surface px-3 py-1.5 text-2xs text-ink-muted transition-colors hover:border-line-strong hover:text-ink disabled:cursor-not-allowed disabled:opacity-50"
              >
                {example}
              </button>
            ))}
          </div>

          <p className="mt-4 border-t border-line pt-3 text-2xs leading-5 text-ink-faint">
            {providerCopy}
          </p>
        </Card>

        {!exchanges.length ? (
          <div className="rounded-panel border border-dashed border-line-strong bg-surface/40 px-6 py-12 text-center">
            <span
              aria-hidden="true"
              className="mx-auto flex h-11 w-11 items-center justify-center rounded-full border border-line bg-subtle text-ink-muted"
            >
              <svg
                viewBox="0 0 16 16"
                className="h-4 w-4"
                fill="none"
                stroke="currentColor"
                strokeWidth="1.4"
                strokeLinecap="round"
                strokeLinejoin="round"
              >
                <path d="M3 3.25h10a1.25 1.25 0 0 1 1.25 1.25v5A1.25 1.25 0 0 1 13 10.75H7.5L4 13.5v-2.75H3A1.25 1.25 0 0 1 1.75 9.5v-5A1.25 1.25 0 0 1 3 3.25Z" />
              </svg>
            </span>
            <p className="mx-auto mt-4 max-w-md text-[13px] leading-6 text-ink-muted">
              Ask a question to search the indexed snapshot. If nothing supports an answer,
              RepoScribe says so instead of guessing.
            </p>
            <p className="mt-3 font-hand text-[20px] leading-none text-ink-faint">
              no evidence, no answer.
            </p>
          </div>
        ) : null}

        <div className="space-y-4">
          {exchanges.map((exchange) => (
            <Card key={exchange.id} className="px-5 py-5">
              <div className="flex gap-3">
                <span
                  aria-hidden="true"
                  className="mt-0.5 grid h-6 w-6 shrink-0 place-items-center rounded-full border border-line bg-subtle font-mono text-[10px] text-ink-faint"
                >
                  Q
                </span>
                <h2 className="min-w-0 text-h3 leading-6 text-ink">{exchange.question}</h2>
              </div>

              {!exchange.answer && !exchange.error ? (
                <p className="mt-4 flex items-center gap-2 border-t border-line pt-4 text-2xs text-ink-muted">
                  <Spinner className="text-accent-strong" /> Retrieving evidence…
                </p>
              ) : null}

              {exchange.error ? (
                <div className="mt-4 border-t border-line pt-4">
                  <ErrorNotice error={exchange.error} onRetry={() => retry(exchange.id)} />
                </div>
              ) : null}

              {exchange.answer ? (
                <div className="mt-4 space-y-4 border-t border-line pt-4">
                  <pre className="whitespace-pre-wrap font-sans text-[13.5px] leading-6 text-ink">
                    {exchange.answer.answer}
                  </pre>

                  {exchange.answer.citations.length ? (
                    <div>
                      <p className="eyebrow">
                        Citations
                        <span className="ml-2 text-line-strong">
                          {exchange.answer.citations.length}
                        </span>
                      </p>
                      <ul className="mt-2 space-y-2">
                        {exchange.answer.citations.map((citation, citationIndex) => (
                          <li
                            key={`${citation.path}-${citationIndex}`}
                            className="overflow-hidden rounded-control border border-line bg-canvas"
                          >
                            <details>
                              <summary className="cursor-pointer px-3 py-2 text-2xs text-ink transition-colors hover:bg-subtle/60">
                                <span className="font-mono">{citation.path}</span>
                                <span className="ml-2 font-mono text-ink-faint">
                                  L{citation.start_line}–{citation.end_line}
                                </span>
                              </summary>
                              <pre className="scroll-region overflow-x-auto border-t border-line bg-subtle px-3 py-2.5 font-mono text-2xs leading-5 text-ink">
                                {citation.excerpt}
                              </pre>
                            </details>
                          </li>
                        ))}
                      </ul>
                    </div>
                  ) : (
                    <p className="rounded-control border border-warn/25 bg-warn-soft px-3 py-2 text-2xs text-warn">
                      No retrieved evidence supported an answer to this question.
                    </p>
                  )}

                  {exchange.answer.limitations.length ? (
                    <ul className="space-y-1.5 text-2xs leading-5 text-ink-faint">
                      {exchange.answer.limitations.map((limitation, limitationIndex) => (
                        <li key={limitationIndex} className="flex gap-2.5">
                          <span
                            aria-hidden="true"
                            className="mt-2 h-1 w-1 shrink-0 rounded-full bg-line-strong"
                          />
                          <span>{limitation}</span>
                        </li>
                      ))}
                    </ul>
                  ) : null}

                  {exchange.answer.follow_up_suggestions.length ? (
                    <div className="flex flex-wrap gap-2 pt-1">
                      {exchange.answer.follow_up_suggestions.map((suggestion) => (
                        <button
                          key={suggestion}
                          type="button"
                          onClick={() => void submit(suggestion)}
                          className="inline-flex items-center rounded-full border border-line bg-surface px-2.5 py-1 text-2xs text-ink-muted transition-colors hover:border-line-strong hover:text-ink"
                        >
                          {suggestion}
                        </button>
                      ))}
                    </div>
                  ) : null}
                </div>
              ) : null}
            </Card>
          ))}
        </div>

        <p className="text-2xs leading-5 text-ink-faint">
          Repository text is treated as untrusted data. Instructions inside a README cannot change
          what RepoScribe is allowed to do.{" "}
          <Link to={`/r/${repository.id}/settings`} className="text-accent-strong hover:underline">
            Review provider settings
          </Link>
        </p>
      </div>
    </div>
  );
}
